package com.dbtool.carplay.api.developer

/**
 * **敏感值的统一脱敏口径**（PATCH-0076，2026-10-11）。
 *
 * ## 为什么要有这么一个小对象
 *
 * 车主口径（verbatim）：*"这些都是明文，我需要你默认值隐藏，不能别人看见"* ——
 * 指的是调试反连隧道的端点（服务器地址）与口令，它们会出现在**三个**地方：
 *
 * | 出现的地方 | 谁看得到 |
 * | --- | --- |
 * | 开发者页的输入框 | 站在车机前的人（截图里就是这一处） |
 * | 应用日志（`appendLog` / `Log.i`） | 车机屏幕上的日志面板 + **诊断包里** |
 * | `system/effective_settings.txt`（诊断包） | **上传到服务器**，等于谁都能看 |
 *
 * 三处各写一份"打码"逻辑，迟早有一处漏掉（现在就是：界面与密钥打了码，
 * 而**服务器地址**在日志与诊断包里是原文）。所以口径收在这里：
 *
 * > **只报"有没有 + 多长"，绝不落原值**；
 * > 需要看/改原值时，人自己去开发者页（那里是打码输入框，点进去才可见）。
 *
 * ⚠️ 这条口径**只解决"被看见"**：值本身若写死在源码里，拿到 APK 的人仍可反编译出来。
 * 要连那一层也堵住，得把默认值改成"构建期注入 + 不随包分发"（见 PATCHES 台账里的待决项），
 * 或直接轮换口令。**不要**因为这里打了码就以为包外的人也拿不到。
 */
object CarSensitiveText {

    /**
     * 未设置时的显示文案。
     *
     * ⚠️ **半角括号**，与 `CarDiagnosticSettingsDump.NOT_SET` **逐字一致** ——
     * 诊断包是逐行机器解析的，两个地方一个全角一个半角，就会出现"同一份包里有两种未设置"，
     * 解析脚本迟早只认其中一种。
     */
    const val NOT_SET = "(未设置)"

    /**
     * 敏感值（口令 / 端点）的摘要：**只报有没有 + 多长**。
     *
     * 为什么连长度也报：现场要能分辨"没填"与"填了但不对"，而长度是唯一既能分辨、
     * 又不足以还原原值的量；同时它让"是不是还停在出厂默认"这类判断有据可依
     * （默认值的长度是已知常量，但**不写出默认值本身**）。
     */
    fun label(value: String): String =
        if (value.isBlank()) NOT_SET else "(已设置，${value.length} 字符)"

    /** 诊断包要上传 ⇒ 服务器地址同样只报"有没有 + 多长"，不落原值。 */
    fun hostLabel(host: String): String = label(host)
}
